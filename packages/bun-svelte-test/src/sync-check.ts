import { existsSync, readFileSync } from 'node:fs';
import { join, resolve as resolvePath } from 'node:path';

const SVELTE_KIT_TSCONFIG = '.svelte-kit/tsconfig.json';
const APP_TSCONFIG_SPECIFIERS: ReadonlySet<string> = new Set(['$app/tsconfig', '$app/tsconfig.json']);
const APP_TSCONFIG_PATH = 'node_modules/$app/tsconfig.json';
const EXTENDS_PATTERN = /"extends"\s*:\s*"([^"]+)"/;

const missingAppTsconfig = (tsconfigPath: string, extendsTarget: string): Error =>
  new Error(
    [
      `bun-svelte-test: ${tsconfigPath} extends "${extendsTarget}", but ${APP_TSCONFIG_PATH} does not exist.`,
      '',
      'SvelteKit 3 generates that file inside node_modules, so a fresh checkout or a new',
      'git worktree does not have it. Without it, bun cannot resolve `$lib/*`, and you',
      'will see `Cannot find module` errors that look like a loader failure.',
      '',
      'Fix: run `bunx svelte-kit sync` in this package.',
    ].join('\n'),
  );

const missingSvelteKitTsconfig = (tsconfigPath: string, extendsTarget: string): Error =>
  new Error(
    [
      `bun-svelte-test: ${tsconfigPath} extends "${extendsTarget}", but that file does not exist.`,
      '',
      'It is generated by SvelteKit and is gitignored, so a fresh checkout or a new',
      'git worktree will not have it. Without it, bun cannot resolve `$lib/*` and you',
      'will see `Cannot find module` errors that look like a loader failure.',
      '',
      'Fix: run `bunx svelte-kit sync` in this package.',
    ].join('\n'),
  );

export const assertSvelteKitSyncRan = (cwd: string = process.cwd()): void => {
  const tsconfigPath = join(cwd, 'tsconfig.json');
  if (!existsSync(tsconfigPath)) return;

  const extendsTarget = EXTENDS_PATTERN.exec(readFileSync(tsconfigPath, 'utf8'))?.[1];
  if (extendsTarget === undefined) return;

  if (APP_TSCONFIG_SPECIFIERS.has(extendsTarget)) {
    if (existsSync(join(cwd, APP_TSCONFIG_PATH))) return;
    throw missingAppTsconfig(tsconfigPath, extendsTarget);
  }

  if (!extendsTarget.includes(SVELTE_KIT_TSCONFIG)) return;
  if (existsSync(resolvePath(cwd, extendsTarget))) return;
  throw missingSvelteKitTsconfig(tsconfigPath, extendsTarget);
};
